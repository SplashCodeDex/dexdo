enum SmartFabPhase { idle, listening }

class SmartFab extends ConsumerStatefulWidget {
  const SmartFab({super.key});

  @override
  ConsumerState<SmartFab> createState() => _SmartFabState();
}

class _SmartFabState extends ConsumerState<SmartFab> with TickerProviderStateMixin {
  SmartFabPhase _phase = SmartFabPhase.idle;

  // Animation Controllers
  late AnimationController _scaleController;
  late AnimationController _morphController;

  // Gesture slide-to-cancel state tracking
  Offset? _dragStartPoint;
  double _dragXOffset = 0.0;
  bool _isCancelThresholdExceeded = false;

  @override
  void initState() {
    super.initState();

    _scaleController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 250),
    );

    _morphController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 300),
    );
  }

  @override
  void dispose() {
    _scaleController.dispose();
    _morphController.dispose();
    super.dispose();
  }

  void _onLongPressStart(LongPressStartDetails details) {
    if (_phase != SmartFabPhase.idle) return;
    _dragStartPoint = details.globalPosition;
    _dragXOffset = 0.0;
    _isCancelThresholdExceeded = false;
    _startVoiceListening();
  }

  void _onLongPressMoveUpdate(LongPressMoveUpdateDetails details) {
    if (_phase != SmartFabPhase.listening) return;
    if (_dragStartPoint == null) return;
    final double currentX = details.globalPosition.dx;
    final double startX = _dragStartPoint!.dx;
    setState(() {
      // Allow sliding left (negative values). Drag limit is 120 pixels.
      _dragXOffset = (currentX - startX).clamp(-120.0, 0.0);
      final bool wasExceeded = _isCancelThresholdExceeded;
      _isCancelThresholdExceeded = _dragXOffset < -80.0;
      if (_isCancelThresholdExceeded != wasExceeded) {
        if (_isCancelThresholdExceeded) {
          HapticFeedback.heavyImpact();
          ref.read(speechProvider.notifier).setCancelImminent(true);
        } else {
          HapticFeedback.mediumImpact();
          ref.read(speechProvider.notifier).setCancelImminent(false);
        }
      }
    });
  }

  Future<void> _onLongPressEnd(LongPressEndDetails details) async {
    if (_phase == SmartFabPhase.listening) {
      if (_isCancelThresholdExceeded) {
        // Discard recording and clean up
        await ref.read(speechProvider.notifier).cancelListening();
        unawaited(AppHaptics.success());
        ref.read(toastProvider.notifier).showWarning('Voice input cancelled.');
        _resetFab();
        return;
      }

      // Release voice mode
      ref.read(speechProvider.notifier).setProcessing(true);

      // Stop listening and capture transcript
      final speechState = ref.read(speechProvider);
      final finalTranscript = speechState.lastWords.trim();

      await ref.read(speechProvider.notifier).stopListening();

      if (finalTranscript.isNotEmpty) {
        unawaited(AppHaptics.success());
        
        // Parse with Gemini NLP
        final parsed = await ref.read(taskProvider.notifier)
            .parseVoiceCommand(finalTranscript);

        // Create the task with parsed attributes
        await ref.read(taskProvider.notifier).addTask(
          title: parsed.title,
          dueDate: parsed.dueDate,
          priority: parsed.priority,
          category: parsed.category,
        );

        final createdTask = ref.read(taskProvider).tasks.first;

        // Populate subtasks if generated by AI
        if (parsed.subtasks != null && parsed.subtasks!.isNotEmpty) {
          for (var sub in parsed.subtasks!) {
            await ref.read(taskProvider.notifier).addSubtask(createdTask, sub);
          }
        }

        unawaited(AppHaptics.taskCreatedFromVoice());
        ref.read(toastProvider.notifier).showSuccess(
          'Task created: "${parsed.title}"',
          title: 'Voice Task Created',
          actionLabel: 'Undo',
          onAction: () {
            ref.read(taskProvider.notifier).deleteTask(createdTask);
          },
          secondaryActionLabel: 'Edit',
          onSecondaryAction: () {
            if (mounted) {
              Navigator.of(context).push(
                PageRouteBuilder(
                  pageBuilder: (context, animation, secondaryAnimation) => TaskEditorPane(task: createdTask),
                  transitionsBuilder: (context, animation, secondaryAnimation, child) {
                    return FadeTransition(
                      opacity: animation,
                      child: child,
                    );
                  },
                ),
              );
            }
          },
        );
      } else {
        ref.read(toastProvider.notifier).showWarning(
          'No speech recognized. Please try again.',
        );
      }

      ref.read(speechProvider.notifier).setProcessing(false);
      _resetFab();
    }
  }

  Future<void> _startVoiceListening() async {
    setState(() {
      _phase = SmartFabPhase.listening;
    });

    unawaited(AppHaptics.voiceModeEnter());
    unawaited(AudioService.playVoiceTriggerSound());
    unawaited(_morphController.forward());
    unawaited(_scaleController.animateTo(1.0, curve: Curves.elasticOut)); // Grow the mic FAB slightly
    
    // Wait for the custom chime to finish playing (400ms) before muting and starting speech recognizer
    await Future.delayed(const Duration(milliseconds: 400));
    
    // Mute system streams to suppress the default beep
    await AudioService.muteSpeechRecognizerBeep();
    
    // Start voice recording
    await ref.read(speechProvider.notifier).startListening();

    // After 1.2 seconds, restore the audio volumes so device music/systems are normal
    unawaited(Future.delayed(const Duration(milliseconds: 1200), () {
      AudioService.unmuteSpeechRecognizerBeep();
    }));
  }

  void _resetFab() {
    unawaited(ref.read(speechProvider.notifier).cancelListening());
    
    // Always unmute system volume streams when resetting/finishing
    unawaited(AudioService.unmuteSpeechRecognizerBeep());
    
    unawaited(_scaleController.animateTo(0.0, curve: Curves.easeOut).then((_) {
      _scaleController.value = 0.0;
    }));
    unawaited(_morphController.reverse());

    setState(() {
      _phase = SmartFabPhase.idle;
      _dragStartPoint = null;
      _dragXOffset = 0.0;
      _isCancelThresholdExceeded = false;
    });
  }

  @override
  Widget build(BuildContext context) {
    // FAB Button size mapping
    const double fabSize = 56.0;

    return Stack(
      alignment: Alignment.center,
      clipBehavior: Clip.none,
      children: [
        // MASTER FAB GESTURE WRAPPER
        GestureDetector(
          onLongPressStart: _onLongPressStart,
          onLongPressEnd: _onLongPressEnd,
          onLongPressMoveUpdate: _onLongPressMoveUpdate,
          onTap: () {
            // Tap behaviour (Default QuickTaskSheet bottom sheet)
            FocusScope.of(context).unfocus();
            HapticFeedback.mediumImpact();
            showModalBottomSheet(
              context: context,
              isScrollControlled: true,
              backgroundColor: Colors.transparent,
              builder: (context) => const QuickTaskSheet(),
            );
          },
          child: ListenableBuilder(
            listenable: ListNotifier([_scaleController, _morphController]),
            builder: (context, child) {
              final double scale = 1.0 + (_scaleController.value * 0.2); // grows slightly when listening
              final double morph = _morphController.value;

              final isDark = Theme.of(context).brightness == Brightness.dark;
              final Color baseFabColor = _isCancelThresholdExceeded
                  ? Colors.redAccent.withValues(alpha: 0.35)
                  : (isDark ? Colors.black : Colors.white).withValues(alpha: 0.25);
              final Color baseBorderColor = _isCancelThresholdExceeded
                  ? Colors.redAccent.withValues(alpha: 0.5)
                  : (isDark ? Colors.white : Colors.black).withValues(alpha: 0.15);

              return Transform.translate(
                offset: Offset(_dragXOffset, 0.0),
                child: Transform.scale(
                  scale: scale,
                  child: Container(
                    width: fabSize,
                    height: fabSize,
                    decoration: BoxDecoration(
                      shape: BoxShape.circle,
                      boxShadow: [
                        BoxShadow(
                          color: _isCancelThresholdExceeded 
                              ? Colors.redAccent.withValues(alpha: 0.1)
                              : Colors.black.withValues(alpha: 0.15),
                          blurRadius: 8,
                          offset: const Offset(0, 4),
                        ),
                      ],
                    ),
                    child: ClipOval(
                      child: BackdropFilter(
                        filter: ImageFilter.blur(sigmaX: 15, sigmaY: 15),
                        child: Container(
                          decoration: BoxDecoration(
                            shape: BoxShape.circle,
                            color: baseFabColor,
                            border: Border.all(
                              color: baseBorderColor,
                              width: 1.0,
                            ),
                          ),
                          child: Center(
                            child: morph > 0.5
                                ? Icon(
                                    _isCancelThresholdExceeded ? Icons.delete_outline_rounded : Icons.mic_none_rounded,
                                    color: _isCancelThresholdExceeded 
                                        ? Colors.redAccent 
                                        : (isDark ? Colors.white : Colors.black87),
                                    size: 28,
                                  )
                                : Transform.rotate(
                                  angle: morph * math.pi / 4, // rotate add icon slightly, leaving mic unrotated
                                  child: Icon(
                                    Icons.add_rounded,
                                    color: isDark ? Colors.white : Colors.black87,
                                    size: 32,
                                  ),
                                ),
                        ),
                      ),
                    ),
                  ),
                ),
              ),
            );
          },
          ),
        ),
      ],
    );
  }
}

// Utility class to listen to multiple animation controllers
class ListNotifier extends ChangeNotifier {
  ListNotifier(this.listenables) {
    for (final listenable in listenables) {
      listenable.addListener(notifyListeners);
    }
  }

  final List<Listenable> listenables;

  @override
  void dispose() {
    for (final listenable in listenables) {
      listenable.removeListener(notifyListeners);
    }
    super.dispose();
  }
}
